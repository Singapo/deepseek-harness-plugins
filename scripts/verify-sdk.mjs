import assert from 'node:assert/strict';
import { readFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { Context } from '@deepseek-ai/cordis';
import ToolRuntime from '@deepseek-ai/dsh-tools';
import SystemPrompt from '@deepseek-ai/dsh-system-prompt';
import * as taskLens from '../task-lens/index.js';
import * as evidenceLedger from '../evidence-ledger/index.js';

const taskData = JSON.parse(await readFile(new URL('../task-lens/examples/tasks.json', import.meta.url), 'utf8'));
const brief = JSON.parse(await readFile(new URL('../evidence-ledger/examples/brief.json', import.meta.url), 'utf8'));
const ctx = new Context();
const system = ctx.plugin(SystemPrompt);
const runtime = ctx.plugin(ToolRuntime);
const task = ctx.plugin(taskLens);
const ledger = ctx.plugin(evidenceLedger);
await new Promise(resolve => setTimeout(resolve, 50));
assert.ok(ctx.tools, 'Real tools service should initialize');
let call = 0;
const execute = (name, args, signal = new AbortController().signal) => ctx.tools.execute({ callId: `portfolio-test-${++call}`, name, arguments: args, signal });
const taskResult = await execute('task_lens_analyze', { dataset: taskData });
assert.equal(taskResult.isError, false, JSON.stringify(taskResult));
assert.equal(taskResult.value.summary.tasks, 4);
assert.equal(taskResult.value.summary.recovered, 1);
const ledgerResult = await execute('evidence_ledger_audit', { brief });
assert.equal(ledgerResult.isError, false, JSON.stringify(ledgerResult));
assert.equal(ledgerResult.value.summary.invalidQuotes, 1);
assert.equal(ledgerResult.value.summary.statuses.conflict, 1);
const verified = await execute('jiaozhen_verify_data', { requestPath: fileURLToPath(new URL('../evidence-ledger/examples/check-pass.json', import.meta.url)) });
assert.equal(verified.isError, false, JSON.stringify(verified));
assert.equal(verified.value.gate.status, 'passed');
assert.ok(verified.value.gate.verifiedText.includes('20.00%'));
const blocked = await execute('jiaozhen_verify_data', { requestPath: fileURLToPath(new URL('../evidence-ledger/examples/check.json', import.meta.url)) });
assert.equal(blocked.isError, false, JSON.stringify(blocked));
assert.equal(blocked.value.gate.status, 'blocked');
assert.equal(blocked.value.gate.verifiedText, null);
const invalid = await execute('task_lens_analyze', {});
assert.equal(invalid.isError, true);
const controller = new AbortController(); controller.abort();
const cancelled = await execute('evidence_ledger_audit', { brief }, controller.signal);
assert.equal(cancelled.isError, true);
assert.equal((await execute('jiaozhen_verify_data', { requestPath: fileURLToPath(new URL('../evidence-ledger/examples/check-pass.json', import.meta.url)) }, controller.signal)).isError, true);
await task.dispose();
const disposed = await execute('task_lens_analyze', { dataset: taskData });
assert.equal(disposed.isError, true, 'Disposing plugin unregisters tool');
const stillAlive = await execute('evidence_ledger_audit', { brief });
assert.equal(stillAlive.isError, false, 'Other plugin survives independent disposal');
await ledger.dispose(); await runtime.dispose(); await system.dispose();
console.log(JSON.stringify({ sdk: '0.2.1-rc.2', checks: ['real Cordis registration', 'real ToolRuntime dispatch for both plugins', 'new data workflow pass and blocked calls', 'input rejection', 'cancellation', 'independent disposal'], paidModelCalls: 0 }, null, 2));
